#!/usr/bin/env python3
"""Build mutually exclusive test bins from final retained DIAMOND hits."""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Sequence

from reliability_aware.utils.config import PROJECT_ROOT
from reliability_aware.utils.diamond_homology import DiamondSearchConfig
from reliability_aware.utils.diamond_executable import resolve_diamond_executable
from reliability_aware.utils.retained_hit_identity_bins import (
    create_retained_hit_identity_bins,
    get_diamond_version,
)


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Create mutually exclusive identity bins from the final retained "
            "test-to-training DIAMOND hits used by EIHR-PROT homology priors."
        )
    )
    parser.add_argument(
        "--test-fasta",
        type=Path,
        default=PROJECT_ROOT / "data/cleaned_dataset/cleaned_pdb_test.fasta",
    )
    parser.add_argument(
        "--train-fasta",
        type=Path,
        default=PROJECT_ROOT / "diamond_db/train_db.fasta",
        help="The exact training FASTA used to build the DIAMOND database.",
    )
    parser.add_argument(
        "--diamond-hits",
        type=Path,
        default=PROJECT_ROOT / "diamond_db/test_hits.tsv",
        help="Saved shared DIAMOND result; this is never regenerated by this command.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=PROJECT_ROOT / "analysis/retained_hit_identity_bins",
    )
    parser.add_argument(
        "--overwrite-output",
        action="store_true",
        help=(
            "Replace files in an existing output directory. The default refuses "
            "to overwrite an existing analysis."
        ),
    )
    parser.add_argument("--evalue-max", type=float, default=1e-5)
    parser.add_argument("--min-query-coverage", type=float, default=0.30)
    parser.add_argument("--top-k", type=int, default=10)
    parser.add_argument(
        "--threads",
        type=int,
        default=16,
        help="Completed-run DIAMOND thread count to record in provenance.",
    )
    parser.add_argument(
        "--pipeline-log",
        type=Path,
        default=PROJECT_ROOT / "pipeline.log",
        help="Optional completed-run log used as a provenance artifact.",
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    if args.top_k <= 0 or args.threads <= 0:
        raise ValueError("--top-k and --threads must be positive")
    if not 0.0 <= args.min_query_coverage <= 1.0:
        raise ValueError("--min-query-coverage must be between 0 and 1")
    if args.evalue_max < 0:
        raise ValueError("--evalue-max must be non-negative")
    for path in (args.test_fasta, args.train_fasta, args.diamond_hits):
        if not path.is_file():
            raise FileNotFoundError(f"Required input artifact does not exist: {path}")
    if (
        args.output_dir.exists()
        and any(args.output_dir.iterdir())
        and not args.overwrite_output
    ):
        raise FileExistsError(
            f"Output directory is not empty: {args.output_dir}. "
            "Pass --overwrite-output only to replace this analysis output."
        )

    diamond_executable = resolve_diamond_executable()
    config = DiamondSearchConfig(
        evalue_max=args.evalue_max,
        min_query_coverage=args.min_query_coverage,
        max_target_seqs=50,
        top_k=args.top_k,
        sensitivity="sensitive",
        iterate=True,
        threads=args.threads,
    )
    result = create_retained_hit_identity_bins(
        test_fasta=args.test_fasta,
        train_fasta=args.train_fasta,
        hits_tsv=args.diamond_hits,
        output_dir=args.output_dir,
        config=config,
        diamond_version=get_diamond_version(diamond_executable),
        pipeline_log=args.pipeline_log,
    )
    print(f"Saved mutually exclusive retained-hit identity bins to: {args.output_dir}")
    for row in result["summary"]:
        print(f"{row['category']}: {row['protein_count']}")
    print(
        "Validated "
        f"{result['validation']['test_protein_count']} unique test proteins with "
        "one assignment each."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
